    public void loadTabelaManutencao() {
DefaultTableModel modelo = (DefaultTableModel) tblManutencao.getModel();
        modelo.setNumRows(0);

        for (Manutencao obj : dao.listaManutencao()) {
            
            String dataFmt = "";
            if(obj.getDataManutencao() != null){
                dataFmt = obj.getDataManutencao().format(formatter);
            }

           
            String snMostrar = (obj.getImpressora() != null) 
                    ? obj.getImpressora().getSerialNumber() 
                    : obj.getHistoricoSN();

            Object[] linha = {
                obj,        
                snMostrar,  
                dataFmt     
            };
            modelo.addRow(linha);
        }
    }
    

