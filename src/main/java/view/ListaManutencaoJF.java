    private void configurarTabela() {
var colunaModelo = tblManutencao.getColumnModel().getColumn(0);

        colunaModelo.setCellRenderer(new javax.swing.table.DefaultTableCellRenderer() {
            @Override
            public java.awt.Component getTableCellRendererComponent(javax.swing.JTable table, Object value,
                    boolean isSelected, boolean hasFocus, int row, int column) {

                super.getTableCellRendererComponent(table, value, isSelected, hasFocus, row, column);

                if (value instanceof Manutencao) {
                    Manutencao manu = (Manutencao) value;
                    
                    if (manu.getImpressora() != null && manu.getImpressora().getModelo() != null) {
                        setText(manu.getImpressora().getModelo().getDescricao());
                    } else {

                        String hist = manu.getHistoricoModelo();
                        setText((hist != null ? hist : "Desconhecida") + " (Excluída)");
                    }
                }
                return this;
            }
        });
    }
    private void btnNovoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnNovoActionPerformed
        CadastroManutencaoJD telaCadastro = new CadastroManutencaoJD(this, rootPaneCheckingEnabled);
        telaCadastro.setVisible(true);

        Manutencao novo = telaCadastro.getManutencao();

        if (novo != null) {
            try {
                dao.persist(novo);
                loadTabelaManutencao();
            } catch (Exception ex) {
                System.err.println("Erro ao adicionar Manutenção: " + ex);
                JOptionPane.showMessageDialog(this, "Erro: " + ex.getMessage());
            }
        }
    }//GEN-LAST:event_btnNovoActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        if (tblManutencao.getSelectedRow() != -1) {
            Manutencao objSelecionado = (Manutencao) tblManutencao.getValueAt(tblManutencao.getSelectedRow(), 0);

            CadastroManutencaoJD telaEdicao = new CadastroManutencaoJD(this, true);
            telaEdicao.setManutencao(objSelecionado); // Passa os dados
            telaEdicao.setVisible(true);

            Manutencao objRetorno = telaEdicao.getManutencao();

            if (objRetorno != null) {
                try {
                    dao.persist(objRetorno);
                    loadTabelaManutencao();
                } catch (Exception ex) {
                    JOptionPane.showMessageDialog(this, "Erro ao editar: " + ex.getMessage());
                }
            }
        } else {
            JOptionPane.showMessageDialog(rootPane, "Selecione uma manutenção para editar.");
        }    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnRemoverActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRemoverActionPerformed
if (tblManutencao.getSelectedRow() != -1) {
            Manutencao obj = (Manutencao) tblManutencao.getModel().getValueAt(tblManutencao.getSelectedRow(), 0);
            
            String desc = (obj.getImpressora() != null) 
                    ? obj.getImpressora().getModelo().getDescricao() 
                    : obj.getHistoricoModelo() + " (Excluída)";
            
            int op_remover = JOptionPane.showConfirmDialog(rootPane, "Tem certeza que deseja remover o registro de manutenção de:\n" + desc + "?");
            
            if (op_remover == JOptionPane.YES_OPTION) {
                try {
                    dao.remover(obj);
                    loadTabelaManutencao();
                    JOptionPane.showMessageDialog(rootPane, "Registro removido com sucesso!");
                } catch (Exception ex) {
                    JOptionPane.showMessageDialog(rootPane, "Erro ao remover: " + ex.getMessage());
                }
            }
        } else {
            JOptionPane.showMessageDialog(rootPane, "Selecione uma linha");
        
        }    }//GEN-LAST:event_btnRemoverActionPerformed

